def subtitles_vf(srt_path):
    """The ONE burn-in path for subtitles (invariant 11 - reuse, never a second
    implementation). Returns the ffmpeg -vf filter string for burning srt_path
    in as a hard subtitle, or None if srt_path is falsy / does not exist -
    callers use None to mean "cut without subtitles" rather than special-casing
    that themselves.

    ffmpeg's subtitles filter needs a forward-slash path and the drive colon
    escaped, or it reads "C" as a protocol and silently drops them.
    MarginV=52 clears the burnt-in shot slug, which sits at h-34 - at the
    default MarginV the caption sat on top of it and both became unreadable.
    Any new caller (assembly, animatic, future reel cuts) gets that fix for
    free by calling this instead of building its own filter string."""
    if not srt_path or not os.path.exists(srt_path):
        return None
    esc = srt_path.replace("\\", "/").replace(":", "\\:")
    # Fontsize 11, down from 16, which is Geoff's "about 30% smaller"
    # (16 * 0.7 = 11.2). MarginV 10 drops the caption to the BOTTOM of the
    # frame; it was 52 to clear a burnt-in shot slug that the letterboxed
    # path no longer puts over the picture. Callers that letterbox
    # (letterbox_vf) place captions in the black bar below the picture
    # instead, so nothing covers the image at all.
    return ("subtitles='%s':force_style='FontName=DejaVu Sans,Fontsize=%d,"
            "PrimaryColour=&H00FFFFFF,BackColour=&H80000000,BorderStyle=3,"
            "Outline=1,MarginV=10'" % (esc, CAPTION_FONTSIZE))


# Letterbox geometry. Kept as constants so the caption margin and the pad
# height cannot drift apart: a caption taller than the bar lands on the
# picture, which is the exact thing letterboxing is here to prevent.
# Geoff, 2026-09-06: "make text smaller, about 30% smaller". 16 * 0.7 = 11.2.
CAPTION_FONTSIZE = 11
LETTERBOX_TOP = 34
LETTERBOX_BOTTOM = 46


def letterbox_vf(srt_path, slug=None, width=None, height=None):
    """-> an ffmpeg -vf that pads the picture into a black letterbox and puts
    the SUBTITLES IN THE BOTTOM BAR, with an optional slug in the top bar.

    Geoff, 2026-09-06: "Have it at the bottom of the frame or in a black
    letter box below the frame. Top letterbox could be the version name."

    Nothing is drawn over the picture. That is the point: a burned-in caption
    cannot be removed later, so the less of the frame it touches the better,
    and a reviewer reading a caption is not looking at the acting underneath
    it anyway.

    Returns None when there is nothing to burn, matching subtitles_vf()'s
    contract so callers keep using None to mean "no subtitles".
    """
    if not srt_path or not os.path.exists(srt_path):
        if not slug:
            return None
    parts = ["pad=iw:ih+%d+%d:0:%d:black" % (LETTERBOX_TOP, LETTERBOX_BOTTOM,
                                             LETTERBOX_TOP)]
    if slug:
        # Escaped for the filter parser the same way FONT is used above:
        # a bare colon reads as an option separator and a bare backslash as
        # an escape, and either one silently breaks the whole chain.
        safe = (str(slug).replace("\\", "\\\\").replace(":", "\\:")
                .replace("'", "").replace(",", " "))
        parts.append("drawtext=fontfile='%s':text='%s':fontcolor=white@0.85:"
                     "fontsize=13:x=(w-text_w)/2:y=%d"
                     % (FONT, safe, max(2, (LETTERBOX_TOP - 13) // 2)))
    if srt_path and os.path.exists(srt_path):
        esc = srt_path.replace("\\", "/").replace(":", "\\:")
        # MarginV is measured from the bottom of the PADDED frame, so it puts
        # the caption inside the bottom bar rather than over the picture.
        # FONT SIZE IS RELATIVE TO FRAME HEIGHT, so the SAME Fontsize renders
        # BIGGER here than in subtitles_vf: padding the frame to 560 makes
        # libass scale every glyph by 560/480. Measured on identical cuts:
        # 17.5px of glyph in the letterbox against 15px in frame, a ratio of
        # 1.167, which is exactly 560/480.
        #
        # That silently broke Geoff's actual instruction. He asked for "about
        # 30% smaller"; the in-frame option delivered 31% and the letterbox
        # only 20%, from the same number in the same file. Derive the size from
        # the pad instead of hardcoding it, so changing LETTERBOX_TOP or
        # LETTERBOX_BOTTOM cannot resize the captions behind our backs again.
        pic_h = float(height or 480)
        size = CAPTION_FONTSIZE * pic_h / (pic_h + LETTERBOX_TOP + LETTERBOX_BOTTOM)
        parts.append("subtitles='%s':force_style='FontName=DejaVu Sans,"
                     "Fontsize=%.1f,PrimaryColour=&H00FFFFFF,BorderStyle=1,"
                     "Outline=0,Shadow=0,MarginV=8'" % (esc, size))
    return ",".join(parts)


def cmd_episode(sg):
    """Stitch the act animatics into one episode cut, with subtitles burned in.

    Geoff asked for subtitles rather than voices until real recordings exist, so
    the review artifact has to carry them. They are BURNED IN, not muxed as a
    soft track: the ShotGrid review player is where this gets watched and a soft
    track it will not display is the same as no subtitles at all.

    The srt is written beside the movie regardless, because a burned-in caption
    cannot be corrected and a sidecar can."""
    parts, missing = [], []
    for code in SEQ_ORDER:
        seq = sg.find_one("Sequence", [["project", "is", PROJ], ["code", "is", code]], ["code"])
        if seq is None:
            missing.append("%s (no such sequence)" % code)
            continue
        vs = sg.find("Version", [["project", "is", PROJ],
                                 ["entity", "is", {"type": "Sequence", "id": seq["id"]}],
                                 ["sg_stage", "is", "animatic"]],
                     ["code", "sg_path_to_movie", "created_at"])
        vs = [v for v in vs if (v.get("sg_path_to_movie") or "")
              and os.path.exists(v["sg_path_to_movie"])]
        if not vs:
            missing.append("%s (no animatic Version with media)" % code)
            continue
        vs.sort(key=lambda v: v.get("created_at") or 0)
        parts.append((code, vs[-1]))
    if missing:
        # Same contract as the sequence animatic: refuse rather than ship a cut
        # that is quietly missing an act.
        log("REFUSED: cannot cut the episode, %d act(s) not ready: %s"
            % (len(missing), "; ".join(missing)))
        return 2

    os.makedirs(ANIMATICS, exist_ok=True)
    work = os.path.join(ANIMATICS, "_work_episode")
    os.makedirs(work, exist_ok=True)
    lst = os.path.join(work, "concat.txt")
    with open(lst, "w", encoding="utf-8") as fh:
        for _, v in parts:
            fh.write("file '%s'\n" % v["sg_path_to_movie"].replace("\\", "/"))

    n = 1
    while os.path.exists(os.path.join(ANIMATICS, "%s_animatic_v%03d.mp4" % (EP.code, n))):
        n += 1
    out = os.path.join(ANIMATICS, "%s_animatic_v%03d.mp4" % (EP.code, n))

    cmd = [FFMPEG, "-n", "-f", "concat", "-safe", "0", "-i", lst]
    subs = ""
    vf = subtitles_vf(CAPTIONS)
    if vf:
        cmd += ["-vf", vf]
        subs = " with burned-in subtitles"
    else:
        log("NOTE: no %s, cutting without subtitles" % os.path.basename(CAPTIONS))
    cmd += ["-c:v", "libx264", "-profile:v", "high", "-pix_fmt", "yuv420p",
            "-crf", "20", "-movflags", "+faststart", out]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if not os.path.exists(out) or os.path.getsize(out) == 0:
        log("encode failed: %s" % (r.stderr or "")[-300:])
        return 1

    dur = subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration",
                          "-of", "default=nw=1:nk=1", out], capture_output=True, text=True)
    seconds = float((dur.stdout or "0").strip() or 0)
    code = "%s_ANIMATIC_v%03d" % (EP.code, n)

    # --- D6_COMPONENTS: same aggregate reasoning as cmd_animatic, one level up
    # (acts instead of shots). No single anchor: this Version has no `entity`
    # at all (project-wide cut).
    wf_hash = PROV.workflow_hash_from_text(
        "episode_concat:" + ",".join(code for code, _v in parts) + "|subs=" + subs)
    v = PUB.publish_version(
        sg, project=PROJ, entity=None, code=code,
        media_path=out,
        description=("Full episode animatic from %d acts. Duration %.2fs (%.2f min)%s. "
                     "Reference only, on request (D8) - not an approval gate for the pilot."
                     % (len(parts), seconds, seconds / 60.0, subs)),
        stage="episode",
        first_frame=1001, last_frame=1000 + int(seconds * 24),
        character="aggregate of %d act(s): %s" % (len(parts), ", ".join(c for c, _v in parts)),
        set_="aggregate - see linked act animatics, no single set",
        action="episode assembly: concatenation of act animatics%s" % subs,
        camera="n/a - assembly of pre-cut animatics, no camera move of its own",
        style="n/a - inherits each act's own style, not restyled here",
        workflow_hash=wf_hash, anchor_version_id=None, log=log)
    log("%s: %d acts, %.2fs (%d:%02d)%s -> Version %d"
        % (code, len(parts), seconds, int(seconds // 60), int(seconds % 60), subs, v["id"]))
    log("  %s" % out)
    return 0


