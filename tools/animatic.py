    _fd, _srt = _tf.mkstemp(suffix=".srt")
    os.close(_fd)
    with open(_srt, "w", encoding="utf-8") as _f:
        _f.write("1\n00:00:00,000 --> 00:00:01,000\nPILOTCHARB: hi\n")

    _plain = subtitles_vf(_srt)
    ck("caption font is 11, about 30 percent down from 16 as asked",
       "Fontsize=11" in _plain and "Fontsize=16" not in _plain)
    ck("caption sits at the BOTTOM of frame, not the old slug-clearing MarginV=52",
       "MarginV=10" in _plain and "MarginV=52" not in _plain)

