def still_for_shot(shot, sg=None):
    """-> the still to hold for this shot's duration, or None.

    THE APPROVED PANEL FIRST, then the board. This module's OWN docstring
    already says so -- "V2 demotes it. The approved PANEL is the spine" -- and
    the code went on requiring a board file that V2 stopped producing. Measured
    2026-09-05: SHOW01 carries 133 panel Versions and ZERO boards, so
    requesting an animatic on a fully approved sequence refused with "2 shot(s)
    have no board" on shots that had both an approved panel and a finished
    video. A stage unreachable for the only episode in production.

    The board path is kept, not replaced: an episode that does have boards
    still animatics from them, and boards remain the cheaper artefact for a
    sequence whose panels are not approved yet. Preference, not substitution.
    """
    # sg_approved_panel is an entity LINK ({type,id,name}), NOT a path -- I
    # read it as one and it silently returned None for every shot, which would
    # have looked exactly like "no panel approved". Resolve the Version and ask
    # it where its media is.
    link = shot.get("sg_approved_panel") or {}
    if sg is not None and link.get("id"):
        try:
            v = sg.find_one("Version", [["id", "is", link["id"]]],
                            ["sg_path_to_movie"])
        except Exception:                                         # noqa: BLE001
            v = None
        ap = (v or {}).get("sg_path_to_movie")
        if ap and os.path.isfile(ap):
            return ap
    board = os.path.join(BOARDS, "%s_BRD_v001.png" % shot["code"])
    return board if os.path.exists(board) else None


def board_task(sg, shot):
    t = sg.find_one("Task", [["entity", "is", {"type": "Shot", "id": shot["id"]}],
                             ["step.Step.short_name", "is", BOARD_STEP]], ["content"])
    if t:
        return t
    step = sg.find_one("Step", [["short_name", "is", BOARD_STEP],
                                ["entity_type", "is", "Shot"]], ["code"])
    if step is None:
        step = sg.create("Step", {"short_name": BOARD_STEP, "code": "Board",
                                  "entity_type": "Shot"})
    return sg.create("Task", {"project": PROJ, "entity": {"type": "Shot", "id": shot["id"]},
                              "step": step, "content": "Board"})


def make_board(sg, shot):
    """One still per shot, at board fidelity. Deliberately the SAME composition
    path as video so the board is a true preview, not a different picture."""
    # D15: same defense-in-depth choke point as genvideo_worker.generate() --
    # sg_gen_prompt is not normally script-beat-formatted, but strip here
    # anyway, at the point this text becomes a GPU call, rather than trust
    # every upstream writer (invariant 11).
    prompt = DG.strip_dialogue_for_prompt(shot.get("sg_gen_prompt") or "").strip()
    if not prompt:
        return None, "sg_gen_prompt is empty"
    pre, suf, neg = sequence_style(sg, shot)
    frag = fragments(sg, shot)
    if frag:
        prompt = prompt.rstrip(" ,.") + ", " + frag
    if pre and pre.strip().lower() not in prompt.lower():
        prompt = pre.strip() + " " + prompt
    if suf and suf.strip().lower() not in prompt.lower():
        prompt = prompt.rstrip(" ,.") + suf
    prompt = " ".join(prompt.split())
    negative = neg or "blurry, distorted, watermark, text"

    size = (shot.get("sg_gen_size_wxh") or "768x432").lower().split("x")
    prefix = "brd_%s" % shot["code"].lower()
    seed = int(shot.get("sg_gen_seed") or 1000)
    cmd = [PY, WRAPPER, "0", "0", "1", "--workflow", TPL_T2V,
           "--comfy-output-dir", OUT_COMFY, "--verify-mode", "disk",
           "--output-prefix", prefix, "--seed-base", str(seed),
           "--expect-outputs", "1", "--timeout", "900",
           "--set", "prompt=%s" % prompt, "--set", "negative_prompt=%s" % negative,
           "--set", "width=%s" % size[0], "--set", "height=%s" % size[1],
           "--set", "length=1", "--set", "steps=%d" % int(shot.get("sg_gen_steps") or 10),
           "--set", "cfg=%s" % (shot.get("sg_gen_cfg") or 5.0)]
    t0 = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True)
    if "PASS:" not in r.stdout:
        return None, "board generation failed: %s" % r.stdout[-300:]
    os.makedirs(BOARDS, exist_ok=True)
    src = os.path.join(OUT_COMFY, "%s_w000_00001_.png" % prefix)
    dst = os.path.join(BOARDS, "%s_BRD_v001.png" % shot["code"])
    import shutil
    shutil.copyfile(src, dst)
    return (dst, prompt, negative, round(time.time() - t0, 1)), None


def publish_board(sg, shot, dst, prompt, negative, took):
    """Publishes through sg_publish.publish_version() (the one contract, per
    docs/METHOD.md) instead of a bare sg.create() +
    sg.upload_thumbnail(). THE FIX: this used to call ONLY upload_thumbnail(),
    never sg.upload(field_name="sg_uploaded_movie") - the board was never
    reviewable, only its thumbnail was, which is exactly the 205-Version bug
    the contract exists to close."""
    task = board_task(sg, shot)
    code = "%s_BRD_board_v001" % shot["code"]

    size = (shot.get("sg_gen_size_wxh") or "768x432").lower().split("x")
    steps = int(shot.get("sg_gen_steps") or 10)
    cfg = shot.get("sg_gen_cfg") or 5.0
    subs = {"prompt": prompt, "negative_prompt": negative, "width": size[0],
            "height": size[1], "length": "1", "steps": str(steps), "cfg": str(cfg)}
    wf_hash = PROV.workflow_hash_from_template(TPL_T2V, subs)
    char_codes, set_codes, other_codes = PROV.classify_assets(sg, shot)
    if other_codes:
        set_codes = set_codes + ["(unclassified: %s)" % ", ".join(other_codes)]
    pre, suf, _neg = sequence_style(sg, shot)

    v = PUB.publish_version(
        sg, project=PROJ, entity={"type": "Shot", "id": shot["id"]}, code=code,
        media_path=dst, sg_task=task,
        description="Storyboard frame. Approve the BOARD before video spends GPU.",
        stage="board",
        extra_fields={"sg_prompt_final__as_sent_": prompt,
                     "sg_negative_final__as_sent_": negative,
                     "sg_gen_seconds": took, "sg_model": "wan2.2_ti2v_5B_fp16"},
        # --- D6_COMPONENTS: a board is a first-generation still, straight
        # from the shot's own prompt - it has no upstream anchor (it IS the
        # thing a later panel/video will anchor to, per D6/Phase 6).
        character=", ".join(char_codes) or "none linked",
        set_=", ".join(set_codes) or "none linked",
        action=(shot.get("sg_gen_prompt") or "").strip() or "(sg_gen_prompt was empty)",
        camera="n/a - no camera field on Shot yet (Phase 5 panel stage); "
               "frame %sx%s" % (size[0], size[1]),
        style=("prefix=%r suffix=%r" % (pre, suf)) if (pre or suf)
              else "none (no style set on this shot's Sequence)",
        workflow_hash=wf_hash, anchor_version_id=None, log=log)
    return v, code


def cmd_boards(sg, limit):
    shots = sg.find("Shot", [["project", "is", PROJ], ["sg_stage", "is", "board"]],
                    ["code", "assets", "sg_sequence", "sg_gen_prompt", "sg_gen_size_wxh",
                     "sg_gen_steps", "sg_gen_cfg", "sg_gen_seed"],
                    order=[{"field_name": "code", "direction": "asc"}])[:limit]
    if not shots:
        log("no shots at sg_stage=board")
        return 0
    if not comfy_start():
        log("cannot start ComfyUI")
        return 1
    n = 0
    for s in shots:
        out, err = make_board(sg, s)
        if err:
            sg.update("Shot", s["id"], {"sg_gen_log": err[:400], "sg_stage": "prompt"})
            log("  %s ERROR %s" % (s["code"], err.splitlines()[0][:90]))
            continue
        dst, prompt, negative, took = out
        v, code = publish_board(sg, s, dst, prompt, negative, took)
        sg.update("Shot", s["id"], {"sg_stage": "keyframe",
                                    "sg_gen_log": "board %s published (%.1fs)" % (code, took)})
        log("  %s -> %s (%.1fs)" % (s["code"], code, took))
        n += 1
    comfy_stop()
    log("boards published: %d" % n)
    return 0


def cmd_animatic(sg, seq_code):
    """Hold each board for its real duration, in cut order, burn in shot code and
    timecode. Called only on explicit request (D8) - a reference cut for
    checking timing by eye, not an approval gate anything downstream waits
    on."""
    seq = sg.find_one("Sequence", [["project", "is", PROJ], ["code", "is", seq_code]], ["code"])
    if seq is None:
        log("no sequence %s" % seq_code)
        return 1
    shots = sg.find("Shot", [["project", "is", PROJ], ["sg_sequence", "is", seq]],
                    ["code", "sg_gen_frames", "sg_cut_order", "sg_approved_panel"],
                    order=[{"field_name": "sg_cut_order", "direction": "asc"}])
    missing, clips = [], []
    os.makedirs(ANIMATICS, exist_ok=True)
    work = os.path.join(ANIMATICS, "_work_%s" % seq_code)
    os.makedirs(work, exist_ok=True)
    for s in shots:
        board = still_for_shot(s, sg)
        if not board:
            missing.append(s["code"])
            continue
        frames = int(s.get("sg_gen_frames") or 49)
        seconds = frames / 24.0
        clip = os.path.join(work, "%s.mp4" % s["code"])
        if not os.path.exists(clip):
            label = "%s   %.2fs" % (s["code"], seconds)
            vf = ("scale=768:432,fps=24,"
                  "drawtext=fontfile='%s':text='%s':x=12:y=h-34:fontsize=18:"
                  "fontcolor=white:box=1:boxcolor=black@0.6" % (FONT, label))
            subprocess.run([FFMPEG, "-y", "-loop", "1", "-i", board, "-t", "%.3f" % seconds,
                            "-vf", vf, "-c:v", "libx264", "-profile:v", "high",
                            "-pix_fmt", "yuv420p", "-crf", "20", clip],
                           capture_output=True, text=True)
        if os.path.exists(clip) and os.path.getsize(clip) > 0:
            clips.append(clip)
        else:
            missing.append(s["code"] + " (encode failed)")
    if missing:
        log("REFUSED: %d shot(s) have no board: %s" % (len(missing), ", ".join(missing[:12])))
        return 2
    lst = os.path.join(work, "concat.txt")
    with open(lst, "w", encoding="utf-8") as fh:
        for c in clips:
            fh.write("file '%s'\n" % c.replace("\\", "/"))
    n = 1
    while os.path.exists(os.path.join(ANIMATICS, "%s_animatic_v%03d.mp4" % (seq_code, n))):
        n += 1
    out = os.path.join(ANIMATICS, "%s_animatic_v%03d.mp4" % (seq_code, n))
    r = subprocess.run([FFMPEG, "-n", "-f", "concat", "-safe", "0", "-i", lst,
                        "-c:v", "libx264", "-profile:v", "high", "-pix_fmt", "yuv420p",
                        "-crf", "20", "-movflags", "+faststart", out],
                       capture_output=True, text=True)
    if not os.path.exists(out) or os.path.getsize(out) == 0:
        log("encode failed: %s" % (r.stderr or "")[-200:])
        return 1
    dur = subprocess.run([FFPROBE, "-v", "error", "-show_entries", "format=duration",
                          "-of", "default=nw=1:nk=1", out], capture_output=True, text=True)
    seconds = float((dur.stdout or "0").strip() or 0)
    code = "%s_ANIMATIC_v%03d" % (seq_code, n)

    # --- D6_COMPONENTS: an animatic is a concatenation of many shots' boards -
    # there is no single character/set/action/camera the way a per-shot
    # generation has one, and no single anchor. Recording that plainly (which
    # shots, how many) beats leaving the fields blank, which would read as "this
    # publisher forgot," not "this publisher is an aggregate by design."
    wf_hash = PROV.workflow_hash_from_text(
        "animatic_concat:" + ",".join(sorted(s["code"] for s in shots)))
    v = PUB.publish_version(
        sg, project=PROJ, entity={"type": "Sequence", "id": seq["id"]}, code=code,
        media_path=out,
        description=("Animatic from %d boards. Duration %.2fs. "
                     "Reference only, on request (D8) - not an approval "
                     "gate; nothing downstream waits on this Version."
                     % (len(clips), seconds)),
        stage="animatic",
        first_frame=1001, last_frame=1000 + int(seconds * 24),
        character="aggregate of %d shot(s): %s"
                  % (len(shots), ", ".join(s["code"] for s in shots)[:800]),
        set_="aggregate - see linked shots, no single set",
        action="animatic assembly: %d boards held to their sg_gen_frames duration, "
               "concatenated in cut order" % len(clips),
        camera="n/a - assembly of stills, no camera move of its own",
        style="n/a - inherits each board's own style, not restyled here",
        workflow_hash=wf_hash, anchor_version_id=None, log=log)
    target = sg.find_one("Sequence", [["id", "is", seq["id"]]], ["sg_target_seconds"])
    tgt = (target or {}).get("sg_target_seconds")
    delta = ("" if not tgt else "  target %ss, delta %+.1fs" % (tgt, seconds - float(tgt)))
    sg.update("Sequence", seq["id"],
              {"sg_gen_log": "animatic %s: %d boards, %.2fs%s" % (code, len(clips), seconds, delta),
               "sg_stage": "animatic"})
    log("%s: %d boards, %.2fs%s -> Version %d" % (code, len(clips), seconds, delta, v["id"]))
    return 0


